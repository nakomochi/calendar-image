// Every themed field is either taken from the incoming theme or reset to the
// DEFAULT_STYLE value. If we let unset fields fall through, the previously
// applied theme's opinions (e.g. Sakura's weekendStyle) would silently leak
// into the next theme.
export function applyTheme(current: CalendarStyle, theme: Theme): CalendarStyle {
  const next = { ...current };
  for (const key of THEME_KEYS) {
    const v = theme.style[key];
    (next as Record<string, unknown>)[key] = v !== undefined ? v : DEFAULT_STYLE[key];
  }
  return next;
}

// A theme's preview needs the full style (with defaults filled in) so the
// preview card can render meaningfully without depending on the current style.
export function themeStyle(theme: Theme): CalendarStyle {
  return { ...DEFAULT_STYLE, ...theme.style };
}
